for i, num in enumerate(numbers):

    print(f"\nChecking: {num}")

    contact = InputPhoneContact(
        client_id=i,
        phone=str(num),
        first_name='test',
        last_name=''
    )

    result = client(ImportContactsRequest([contact]))

    # Telegram returns users found on TG
    if result.users:
        print(f"{num} --> ON TELEGRAM")

        # cleanup imported contact
        client(DeleteContactsRequest(
            id=[user.id for user in result.users]
        ))

    else:
        print(f"{num} --> NOT ON TELEGRAM")

    time.sleep(2)

client.disconnect()